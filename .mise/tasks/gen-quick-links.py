# -*- coding: utf-8 -*-

"""
Rewrite QUICK_LINKS.md, the console URL of every AWS resource, one table per
environment, from the local config files. Makes no AWS call. An environment
whose config fails to load gets an error line instead of a table.
"""

from cookiecutter_aws_lbd_demo.paths import path_enum
from cookiecutter_aws_lbd_demo.env import EnvNameEnum
from cookiecutter_aws_lbd_demo.config.api import Config

HEADER = """\
# Quick Links

The console of every AWS resource of this project, by environment.
Sign in to the account of an environment before opening its links.

Generated by `mise run gen-quick-links` from `config/`. Do not edit by hand.
"""

TABLE_HEADER = ["| Resource | Console |", "| :--- | :--- |"]


def row(resource: str, name: str, url: str) -> str:
    return f"| {resource} | [`{name}`]({url}) |"


def devops_rows(c: Config) -> list[str]:
    return [
        row("Lambda layer, every version", c.lambda_layer_name, c.lambda_layer_url),
        row("Lambda layer artifacts", c.s3dir_lambda.uri, c.s3dir_lambda_url),
    ]


def env_rows(c: Config) -> list[str]:
    rows = [
        row(
            "CloudFormation stack, infra", c.cft_stack_name_infra, c.cft_stack_url_infra
        ),
        row("CloudFormation stack, lbd", c.cft_stack_name_lbd, c.cft_stack_url_lbd),
        row(
            "IAM role, Lambda execution", c.iam_role_name_lambda, c.iam_role_url_lambda
        ),
    ]
    for x in c.lambda_functions:
        rows.append(
            row(
                f"Lambda function, {x}",
                c.get_lambda_function_name(x),
                c.get_lambda_function_url(x),
            )
        )
        rows.append(
            row(
                f"CloudWatch log group, {x}",
                c.get_lambda_log_group_name(x),
                c.get_lambda_log_group_url(x),
            )
        )
    rows += [
        row("SSM parameter, config", c.ssm_param_name_config, c.ssm_param_url_config),
        row("S3 folder, data", c.s3dir_data.uri, c.s3dir_data_url),
        row("S3 folder, s3sync source", c.s3dir_source.uri, c.s3dir_source_url),
        row("S3 folder, s3sync target", c.s3dir_target.uri, c.s3dir_target_url),
        row(
            "S3 bucket properties, event notifications",
            c.s3_bucket_data,
            c.s3_bucket_data_properties_url,
        ),
    ]
    return rows


def main():
    configs = {}
    for member in EnvNameEnum.get_workloads():
        try:
            configs[member.value] = Config.load_from_local_config_file(
                env_name=member.value
            )
        except Exception as e:
            print(
                f"ERROR: cannot load the config of {member.value!r}: {type(e).__name__}: {e}"
            )
            configs[member.value] = e
    loaded = [c for c in configs.values() if isinstance(c, Config)]

    lines = [HEADER, f"## {EnvNameEnum.devops.value}", ""]
    if loaded:
        lines += TABLE_HEADER + devops_rows(loaded[0])
    else:
        lines.append("ERROR: the config of every environment failed to load.")
    for env_name, c in configs.items():
        lines += ["", f"## {env_name}", ""]
        if isinstance(c, Config):
            lines += TABLE_HEADER + env_rows(c)
        else:
            # only the type: the message may hold a local path
            lines.append(
                f"ERROR: cannot load the config of `{env_name}`: `{type(c).__name__}`."
            )
    text = "\n".join(lines) + "\n"

    path = path_enum.path_quick_links_md
    if path.exists() and path.read_text(encoding="utf-8") == text:
        print(f"{path} is already up to date")
    else:
        path.write_text(text, encoding="utf-8")
        print(f"Updated {path}")


if __name__ == "__main__":
    main()
