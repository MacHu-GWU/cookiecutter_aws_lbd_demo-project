# -*- coding: utf-8 -*-

"""
Render ``QUICK_LINKS.md``, the console URL of every AWS resource of the project,
one table per environment (``mise run gen-quick-links``). Makes no AWS call.
"""

from __future__ import annotations

from .env import EnvNameEnum
from .config.api import Config
from .paths import path_enum


def load_env_configs() -> dict[str, Config | Exception]:
    """
    The config of every workload environment, by name, or the error raised
    while loading it, such as when its ``-secret`` file is missing.
    """
    configs = {}
    for member in EnvNameEnum.get_workloads():
        try:
            configs[member.value] = Config.load_from_local_config_file(
                env_name=member.value
            )
        except Exception as e:
            configs[member.value] = e
    return configs


def _row(resource: str, name: str, url: str) -> str:
    return f"| {resource} | [`{name}`]({url}) |"


TABLE_HEADER = ["| Resource | Console |", "| :--- | :--- |"]


def render_devops_rows(configs: dict[str, Config]) -> list[str]:
    """
    The rows of the devops table: the layer, the version each environment
    pins, and the layer artifacts in S3.

    :param configs: the configs that loaded, by environment name; at least one.
    """
    c = next(iter(configs.values()))
    rows = [
        _row("Lambda layer, every version", c.lambda_layer_name, c.lambda_layer_url)
    ]
    for env_name, env_c in configs.items():
        v = env_c.lambda_layer_version
        s3dir = env_c.get_s3dir_lambda_layer_version(v)
        url = env_c.get_lambda_layer_version_url(v)
        rows.append(
            _row(
                f"Lambda layer version pinned by {env_name}",
                f"{c.lambda_layer_name}:{v}",
                url,
            )
        )
        rows.append(
            _row(
                f"uv.lock of the layer version pinned by {env_name}",
                s3dir.uri,
                s3dir.console_url,
            )
        )
    rows.append(_row("Lambda layer artifacts", c.s3dir_lambda.uri, c.s3dir_lambda_url))
    return rows


def render_env_rows(c: Config) -> list[str]:
    """
    The rows of the table of one workload environment.
    """
    rows = [
        _row(
            "CloudFormation stack, infra", c.cft_stack_name_infra, c.cft_stack_url_infra
        ),
        _row("CloudFormation stack, lbd", c.cft_stack_name_lbd, c.cft_stack_url_lbd),
        _row(
            "IAM role, Lambda execution", c.iam_role_name_lambda, c.iam_role_url_lambda
        ),
    ]
    for x in c.lambda_functions:
        rows.append(
            _row(
                f"Lambda function, {x}",
                c.get_lambda_function_name(x),
                c.get_lambda_function_url(x),
            )
        )
        rows.append(
            _row(
                f"CloudWatch log group, {x}",
                c.get_lambda_log_group_name(x),
                c.get_lambda_log_group_url(x),
            )
        )
    rows.extend(
        [
            _row(
                "SSM parameter, config", c.ssm_param_name_config, c.ssm_param_url_config
            ),
            _row("S3 folder, data", c.s3dir_data.uri, c.s3dir_data_url),
            _row("S3 folder, s3sync source", c.s3dir_source.uri, c.s3dir_source_url),
            _row("S3 folder, s3sync target", c.s3dir_target.uri, c.s3dir_target_url),
            _row(
                "S3 bucket properties, event notifications",
                c.s3_bucket_data,
                c.s3_bucket_data_properties_url,
            ),
        ]
    )
    return rows


def _error(env_name: str, error: Exception) -> str:
    # only the type: the message may hold a local path
    return f"ERROR: cannot load the config of `{env_name}`: `{type(error).__name__}`."


def render_quick_links(configs: dict[str, Config | Exception]) -> str:
    """
    The content of ``QUICK_LINKS.md``: one section per environment, devops first.
    An environment whose config failed to load gets an error line instead of
    a table, and is left out of the devops table.

    :param configs: from :func:`load_env_configs`.
    """
    loaded = {k: v for k, v in configs.items() if isinstance(v, Config)}
    lines = [
        "# Quick Links",
        "",
        "The console of every AWS resource of this project, by environment.",
        "Sign in to the account of an environment before opening its links.",
        "",
        "Generated by `mise run gen-quick-links` from `config/`. Do not edit by hand.",
        "",
        f"## {EnvNameEnum.devops.value}",
        "",
    ]
    if loaded:
        lines.extend(TABLE_HEADER + render_devops_rows(loaded))
    else:
        lines.append("ERROR: the config of every environment failed to load.")
    for env_name, config in configs.items():
        lines.extend(["", f"## {env_name}", ""])
        if isinstance(config, Config):
            lines.extend(TABLE_HEADER + render_env_rows(config))
        else:
            lines.append(_error(env_name, config))
    return "\n".join(lines) + "\n"


def write_quick_links() -> bool:
    """
    Render ``QUICK_LINKS.md`` from the local config files, printing the error
    of every environment that failed to load.

    :return: whether the file changed.
    """
    configs = load_env_configs()
    for env_name, config in configs.items():
        if isinstance(config, Exception):
            print(
                f"ERROR: cannot load the config of {env_name!r}: {type(config).__name__}: {config}"
            )
    text = render_quick_links(configs)
    path = path_enum.path_quick_links_md
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True
